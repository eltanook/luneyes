// Helper functions
export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug)
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return products.filter((p) => p.categorySlug === categorySlug)
}

export function getProductsByCategories(categorySlugs: string[]): Product[] {
  if (categorySlugs.length === 0) return products
  return products.filter((p) => categorySlugs.includes(p.categorySlug))
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.featured)
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return categories.find((c) => c.slug === slug)
}

export function getCategoryProductCount(categorySlug: string): number {
  return products.filter((p) => p.categorySlug === categorySlug).length
}

export function getAllCategoriesWithCount(): (Category & { productCount: number })[] {
  return categories.map((cat) => ({
    ...cat,
    productCount: getCategoryProductCount(cat.slug),
  }))
}
